import { normalizePhoneToE164 } from './phone';

describe('normalizePhoneToE164', () => {
  it.each([
    ['0988384849', '+593988384849'],
    ['098 838 4849', '+593988384849'],
    ['098-838-4849', '+593988384849'],
    ['(098) 838.4849', '+593988384849'],
    ['988384849', '+593988384849'],
    ['+593988384849', '+593988384849'],
    ['+593 98 838 4849', '+593988384849'],
    ['+593 098 838 4849', '+593988384849'],
    ['00593988384849', '+593988384849'],
    ['593988384849', '+593988384849'],
    ['022345678', '+59322345678'],
    ['(02) 234-5678', '+59322345678'],
    ['072345678', '+59372345678'],
    ['+593 2 234 5678', '+59322345678'],
    ['+44 20 7946 0018', '+442079460018'],
    ['0044 20 7946 0018', '+442079460018'],
    ['+1 (415) 555-0100', '+14155550100'],
  ])('normalizes %s to %s', (input, expected) => {
    expect(normalizePhoneToE164(input)).toBe(expected);
  });

  it.each([
    [''],
    ['   '],
    ['call me at 099 123 4567'],
    ['12345'],
    ['0812345678'],
    ['012345678'],
    ['+0988384849'],
    ['+593 98 838 48'],
    ['099+1234567'],
    ['++593988384849'],
    ['+1234567890123456'],
    ['098838484912'],
  ])('rejects %j', (input) => {
    expect(normalizePhoneToE164(input)).toBeNull();
  });

  it('handles nullish input', () => {
    expect(normalizePhoneToE164(undefined)).toBeNull();
    expect(normalizePhoneToE164(null)).toBeNull();
  });
});
