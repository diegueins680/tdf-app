import { expect } from '@playwright/test';
import path from 'node:path';
import { createHash } from 'node:crypto';

/** Only called inside the owned disposable HTTP/browser fixture. */
export async function verifyNewAccountPublication({ context, owner, config, origin, output, result }) {
  if (config.api !== 'http://127.0.0.1:18886' || config.eventId !== '919143001') throw new Error('Synthetic signup fixture only');
  const page = await context.newPage();
  const guest = `/social/eventos/${config.eventId}?utm_source=synthetic-new-account#momentos`;
  const destination = `/social/eventos/${config.eventId}?utm_source=synthetic-new-account&compose=1#momentos`;
  await page.goto(origin + guest, { waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('link', { name: 'Compartir mis momentos', exact: true })).toBeVisible({ timeout: 30000 });
  await page.getByRole('link', { name: 'Compartir mis momentos', exact: true }).click();
  await expect(page.locator('input[autocomplete="username"]')).toBeVisible({ timeout: 30000 });
  expect(new URL(page.url()).searchParams.get('redirect')).toBe(destination);
  await page.getByRole('button', { name: 'Crear cuenta general', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Crear cuenta', exact: true });
  await expect(dialog).toBeVisible();
  expect(new URL(page.url()).searchParams.get('redirect')).toBe(destination);
  await expect(dialog.locator('#signup-consent-notice')).toBeVisible();
  await expect(dialog.locator('a[href="/account/terms-es.html"]')).toBeVisible();
  await expect(dialog.locator('a[href="/account/privacy-es.html"]')).toBeVisible();
  await dialog.locator('input[autocomplete="email"]').fill('memory.newcomer@persona.test');
  await dialog.locator('input[autocomplete="new-password"]').fill('synthetic-newcomer-password-141');
  const signupResponse = page.waitForResponse(response => response.url() === config.api + '/signup' && response.request().method() === 'POST');
  await dialog.getByRole('button', { name: 'Crear e ingresar', exact: true }).click();
  const signup = await signupResponse;
  expect(signup.status()).toBe(200);
  const payload = signup.request().postDataJSON();
  expect(payload.termsAccepted).toBe(true);
  expect(payload.termsVersion).toBe('tdf-account-terms-v1');
  expect(payload.marketingOptIn).toBe(false);
  const account = await signup.json();
  expect(Number.isSafeInteger(account.partyId) && account.partyId > 0).toBe(true);
  expect(typeof account.token).toBe('string');
  await expect(page).toHaveURL(origin + destination, { timeout: 30000 });
  await expect(page.getByRole('combobox', { name: 'Tipo de recuerdo' })).toBeVisible({ timeout: 30000 });
  const auth = { Authorization: `Bearer ${account.token}` };
  const preference = await context.request.get(config.api + '/social-events/me/memory-invitations', { headers: auth });
  expect(preference.status()).toBe(200);
  expect((await preference.json()).inApp).toBe(false);
  const privateRead = await context.request.get(config.api + '/social-events/events/919143002/moments?extended', { headers: auth });
  expect(privateRead.status()).toBe(404);
  const campaign = await context.request.get(config.api + `/social-events/events/${config.eventId}/memory-invitations`, { headers: auth });
  expect(campaign.status()).toBe(404);
  result.assertions.push('New phone-browser account registers through visible account terms and returns to the exact invitation/composer target without fixture role grants');

  const caption = 'Primer recuerdo sintético de una cuenta nueva';
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jQ1sAAAAASUVORK5CYII=', 'base64');
  await page.getByRole('textbox', { name: 'Describe tu publicación' }).fill(caption);
  await page.locator('input[type="file"]').setInputFiles({ name: 'newcomer-memory.png', mimeType: 'image/png', buffer: png });
  const uploaded = page.waitForResponse(response => response.url() === config.api + `/social-events/events/${config.eventId}/moments/media` && response.request().method() === 'POST');
  const posted = page.waitForResponse(response => response.url() === config.api + `/social-events/events/${config.eventId}/moments` && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Publicar', exact: true }).click();
  const upload = await uploaded; expect(upload.status()).toBe(200);
  const publication = await posted; expect(publication.status()).toBe(200);
  const moment = await publication.json();
  expect(String(moment.emEventId)).toBe(config.eventId);
  expect(String(moment.emAuthorPartyId)).toBe(String(account.partyId));
  expect(/^[1-9]\d*$/.test(String(moment.emId))).toBe(true);
  const media = new URL(moment.emMediaUrl);
  expect(media.origin).toBe('https://assets.persona.test');
  expect(media.pathname.startsWith('/assets/serve/')).toBe(true);
  const asset = await context.request.get(config.api + media.pathname);
  expect(asset.status()).toBe(200);
  const bytes = await asset.body();
  expect(bytes.equals(png)).toBe(true);
  const card = current => current.getByRole('region', { name: /^Publicación de / }).filter({ hasText: caption });
  await expect(card(page)).toBeVisible({ timeout: 30000 });
  await page.reload(); await expect(card(page)).toBeVisible({ timeout: 30000 });
  await card(page).scrollIntoViewIfNeeded();
  await expect(card(page).getByRole('img')).toBeVisible();
  await expect.poll(() => card(page).getByRole('img').evaluate(image => image.naturalWidth)).toBe(1);
  await owner.reload(); await expect(card(owner)).toBeVisible({ timeout: 30000 });
  const after = await context.request.get(config.api + '/social-events/me/memory-invitations', { headers: auth });
  expect(after.status()).toBe(200); expect((await after.json()).inApp).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await card(page).screenshot({ path: path.join(output, 'signup-first-memory-phone.png') });
  result.newAccount = { partyId: account.partyId, momentId: String(moment.emId), assetPath: media.pathname, assetSha256: createHash('sha256').update(bytes).digest('hex'), signupStatus: signup.status(), uploadStatus: upload.status(), publicationStatus: publication.status(), marketingRequested: false, invitationPreferenceBefore: false, invitationPreferenceAfter: false, privateReadStatus: privateRead.status(), organizerCampaignStatus: campaign.status(), fixtureRoleGrants: 0 };
  result.assertions.push('First uploaded photograph is acknowledged by the actual API, returns identical durable bytes and remains visible to its new author and another account after reload');
  result.assertions.push('Registration and first publication leave invitation preference disabled and do not grant private-event or organizer campaign access');
}
