import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const workspaceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(workspaceRoot, 'tdf-hq/assets/feature-registry.json');
const outputPath = path.join(workspaceRoot, 'tdf-mobile/src/features/generatedFeatureRegistry.ts');
const raw = await readFile(sourcePath, 'utf8');
const registry = JSON.parse(raw);
const defaults = registry.defaults ?? {};

const mobileFeatures = registry.features.map((feature) => {
  const merged = {
    ...defaults,
    ...feature,
    description: feature.description ?? defaults.description,
    permissions: feature.permissions ?? defaults.permissions,
    mobilePresentation: feature.mobilePresentation ?? defaults.mobilePresentation,
  };
  return {
    id: merged.id,
    parentId: merged.parentId ?? null,
    webRoute: merged.webRoute ?? null,
    routeType: merged.routeType,
    classification: merged.classification,
    label: merged.label,
    synonyms: merged.synonyms,
    keywords: merged.keywords,
    description: merged.description,
    navigationGroup: merged.navigationGroup ?? null,
    icon: merged.icon,
    breadcrumb: merged.breadcrumb,
    requiredAuth: merged.requiredAuth,
    routeAction: merged.routeAction,
    requiredRoles: merged.requiredRoles,
    requiredModules: merged.requiredModules,
    permissions: merged.permissions,
    featureFlag: merged.featureFlag,
    maturity: merged.maturity,
    globalMenu: merged.globalMenu,
    quickCreate: merged.quickCreate,
    favoriteEligible: merged.favoriteEligible,
    pinEligible: merged.pinEligible,
    recentBehavior: merged.recentBehavior,
    mobilePresentation: merged.mobilePresentation,
    mobileAliases: merged.mobileAliases,
    telemetryId: merged.telemetryId ?? merged.id,
    accessRequestEligible: merged.accessRequestEligible,
    technical: merged.technical,
    searchable: merged.searchable,
    safeLockedDisclosure: merged.safeLockedDisclosure,
    aliases: merged.aliases,
  };
});

const digest = createHash('sha256').update(raw).digest('hex');
const output = `/* This file is generated by scripts/generate-mobile-feature-registry.mjs. */
export const MOBILE_FEATURE_REGISTRY_SOURCE_SHA256 = '${digest}' as const;
export const MOBILE_FEATURE_REGISTRY_VERSION = ${JSON.stringify(registry.registryVersion)} as const;
export const mobileFeatureGroups = ${JSON.stringify(registry.groups, null, 2)} as const;
export const mobileFeatureRegistry = ${JSON.stringify(mobileFeatures, null, 2)} as const;
`;

await writeFile(outputPath, output);
