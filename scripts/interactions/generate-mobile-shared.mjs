import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const mobile = path.resolve(process.env.TDF_MOBILE_ROOT ?? path.join(root, 'tdf-mobile'));
const files = [
  ['tdf-hq-ui/src/api/interactions.ts', 'src/api/interactions.ts'],
  ['tdf-hq-ui/src/features/interactions/model.ts', 'src/features/interactions/model.ts'],
];
for (const [source, output] of files) {
  const content = `// Generated by scripts/interactions/generate-mobile-shared.mjs.\n${await readFile(path.join(root, source), 'utf8')}`;
  const destination = path.join(mobile, output);
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8') !== content) throw new Error(`Interaction shared code drift: ${output}`);
  } else {
    await mkdir(path.dirname(destination), { recursive: true }); await writeFile(destination, content);
  }
}
